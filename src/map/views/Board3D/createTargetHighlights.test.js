import * as THREE from 'three'
import { BOARD_LAYOUT } from '../../layout/boardLayout'
import { createTargetHighlights } from './createTargetHighlights'
import { getTargetHighlightStyle } from '../../contract/targetHighlight'

test('shows all valid hexes, updates colors and clears stale markers without new allocations', () => {
    const geometry = new THREE.BufferGeometry()
    const markers = createTargetHighlights(BOARD_LAYOUT, geometry, geometry)
    const original = markers.group.children.slice()
    const visibleIds = () => markers.group.children.flatMap((m, i) => m.visible ? [BOARD_LAYOUT[i].id] : [])
    expect(visibleIds()).toEqual([])
    const cellIds = BOARD_LAYOUT.map(c => c.id)
    markers.update({ kind: 'placement', cellIds, preview: false })
    markers.animate(0, true)
    expect(visibleIds()).toEqual(cellIds)
    expect(markers.group.children[0].children[0].material.color.getHexString()).toBe(getTargetHighlightStyle('placement').color.slice(1))
    markers.update({ kind: 'move', cellIds: [0, 7], preview: true })
    markers.animate(.1, true)
    expect(visibleIds()).toEqual([0, 7])
    expect(markers.group.children[0].children[0].material.opacity).toBe(.24)
    expect(markers.group.children[0].position.x).toBe(BOARD_LAYOUT[0].x)
    markers.update({ kind: 'attack', cellIds: [14], preview: false })
    markers.animate(.2, true)
    expect(visibleIds()).toEqual([14])
    markers.update(undefined)
    markers.animate(.3, true)
    expect(visibleIds()).toEqual([])
    original.forEach((marker, i) => expect(markers.group.children[i]).toBe(marker))
    geometry.dispose()
    const materials = new Set()
    markers.group.traverse(child => { if (child.material) materials.add(child.material) })
    materials.forEach(material => { material.map?.dispose(); material.dispose() })
})

test('blocked opponent icons are distinct from valid targets and clear on cancellation', () => {
    const geometry = new THREE.BufferGeometry()
    const markers = createTargetHighlights(BOARD_LAYOUT, geometry, geometry)
    const [a,b,c] = markers.group.children
    markers.update({ kind: 'attack', cellIds: [0], preview: true,
        blocked: [{ id: 1, code: 'minimum' }, { id: 2, code: 'protected' }] })
    expect(a.visible).toBe(true)
    expect(a.children[2].visible).toBe(false)
    expect(b.userData.blocked).toBe('minimum')
    expect(c.userData.blocked).toBe('protected')
    expect(b.children[2].visible).toBe(true)
    expect(c.children[2].visible).toBe(true)
    expect(b.children[2].material).not.toBe(c.children[2].material)
    markers.update(undefined)
    markers.animate(0, true)
    expect(markers.group.children.every(marker => !marker.visible)).toBe(true)
    geometry.dispose()
    const materials = new Set()
    markers.group.traverse(child => { if (child.material) materials.add(child.material) })
    materials.forEach(material => { material.map?.dispose(); material.dispose() })
})

test('mixed eligibility keeps a legal highlight and a blocked icon on the same hex', () => {
    const geometry = new THREE.BufferGeometry()
    const markers = createTargetHighlights(BOARD_LAYOUT, geometry, geometry)
    const first = markers.group.children[0]
    markers.update({ kind: 'attack', cellIds: [0], preview: true,
        playerIds: [1], blocked: [{ id: 0, playerId: 2, code: 'hangloose' }] })
    expect(first.visible).toBe(true)
    expect(first.children[0].material.color.getHexString()).toBe(getTargetHighlightStyle('attack').color.slice(1))
    expect(first.children[2].visible).toBe(true)
    expect(first.userData.blocked).toBe('hangloose')
    markers.update({ kind: 'attack', cellIds: [0], preview: true,
        playerIds: [1], blocked: [{ id: 0, playerId: 2, code: 'hangloose' }] }, true)
    expect(first.visible).toBe(true)
    expect(first.children[2].visible).toBe(false)
    expect(first.userData.blocked).toBe('hangloose')
    markers.update(undefined)
    markers.animate(0, true)
    expect(first.visible).toBe(false)
    geometry.dispose()
    const materials = new Set()
    markers.group.traverse(child => { if (child.material) materials.add(child.material) })
    materials.forEach(material => { material.map?.dispose(); material.dispose() })
})

test('mixed actions share a flat two-color perimeter, preserve the center and clear independently', () => {
    const geometry = new THREE.BufferGeometry()
    const markers = createTargetHighlights(BOARD_LAYOUT, geometry, geometry)
    const [both, attackOnly] = markers.group.children
    const mixed = both.getObjectByName('mixed-target-border')
    const originalMeshes = mixed.children.slice()
    markers.update({ kind: 'move', cellIds: [0], preview: true, attackCellIds: [0, 1] })
    expect(both.visible).toBe(true)
    expect(mixed.visible).toBe(true)
    expect(both.children[0].visible).toBe(false)
    expect(both.children[1].visible).toBe(false)
    expect(both.children[3].visible).toBe(false)
    expect(both.children[4].visible).toBe(false)
    expect(mixed.children[1].material.color.getHexString()).toBe(getTargetHighlightStyle('move').color.slice(1))
    expect(mixed.children[3].material.color.getHexString()).toBe(getTargetHighlightStyle('attack').color.slice(1))
    expect(mixed.children[1].geometry.attributes.position.count).toBe(18)
    expect(mixed.children[3].geometry.attributes.position.count).toBe(18)
    expect(mixed.children[1].geometry).toBe(attackOnly.getObjectByName('mixed-target-border').children[1].geometry)
    expect(attackOnly.children[3].visible).toBe(true)
    markers.animate(0, false)
    markers.animate(.1, false)
    expect(both.position.y).toBeCloseTo(.15)
    expect(both.children[4].visible).toBe(false)
    markers.update({ kind: 'move', cellIds: [0], preview: true })
    expect(mixed.visible).toBe(false)
    expect(both.children[0].visible).toBe(true)
    markers.animate(.2, true)
    expect(both.position.y).toBeCloseTo(.41)
    markers.update({ kind: 'move', cellIds: [0], preview: true, attackCellIds: [0] }, true, new Set([0]))
    markers.animate(.3, true)
    expect(both.position.y).toBeCloseTo(.15)
    expect(mixed.children).toEqual(originalMeshes)
    markers.update(undefined)
    markers.animate(.4, true)
    expect(both.visible).toBe(false)
    expect(attackOnly.visible).toBe(false)
    const geometries = new Set(), materials = new Set()
    markers.group.traverse(child => { if (child.geometry) geometries.add(child.geometry); if (child.material) materials.add(child.material) })
    geometries.forEach(g => g.dispose())
    materials.forEach(material => { material.map?.dispose(); material.dispose() })
})

test('single-action floating feedback still animates and clears with reduced motion', () => {
    const geometry = new THREE.BufferGeometry()
    const markers = createTargetHighlights(BOARD_LAYOUT, geometry, geometry)
    const [move, attack] = markers.group.children
    markers.update({ kind: 'move', cellIds: [0], preview: true, attackCellIds: [1] })
    expect(attack.children[3].visible).toBe(true)
    markers.animate(0, false)
    const start = move.position.y
    markers.animate(.1, false)
    expect(move.position.y).toBeGreaterThan(start)
    const reflectionHeight = move.position.y + move.children[4].position.y
    markers.animate(.2, false)
    expect(move.position.y + move.children[4].position.y).toBeCloseTo(reflectionHeight)
    const risenHeight = move.position.y
    markers.update(undefined)
    expect(move.visible).toBe(true)
    markers.animate(.3, false)
    expect(move.position.y).toBeLessThan(risenHeight)
    markers.animate(.4, false)
    markers.animate(.5, false)
    expect(move.visible).toBe(false)
    expect(attack.visible).toBe(false)
    markers.update({ kind: 'move', cellIds: [0], preview: true }, true, new Set([0]))
    markers.animate(.6, true)
    expect(move.position.y).toBeCloseTo(.17)
    markers.update(undefined)
    markers.animate(.7, true)
    expect(move.visible).toBe(false)
    const geometries = new Set(), materials = new Set()
    markers.group.traverse(child => { if (child.geometry) geometries.add(child.geometry); if (child.material) materials.add(child.material) })
    geometries.forEach(g => g.dispose())
    materials.forEach(material => { material.map?.dispose(); material.dispose() })
})
